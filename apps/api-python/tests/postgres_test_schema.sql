-- Base schema for disposable PostgreSQL integration test databases.
--
-- Mirrors the Node API's production PostgreSQL DDL (apps/api/scripts/
-- migrate-sqlite-to-postgres.js) with one reviewed difference: integer
-- primary keys use identity generation instead of a bare
-- "id INTEGER PRIMARY KEY". The Python API inserts rows without
-- supplying ids, so app/schema_check.py requires every id column to be
-- generated (nextval or SQL-standard identity). The deployed schema's
-- actual id defaults must be inspected on the staging copy before the
-- Python API is enabled against any existing database.
--
-- After this file, apply the reviewed migrations in order:
--   migrations/001_api_rate_limits.sql
--   migrations/002_dynamic_data_catalog_and_reconciliation.sql
--   migrations/003_unique_password_reset_tokens.sql (preflight first)
--
-- Use only on a verified disposable database. Never run against
-- production or any database holding real data.

BEGIN;

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    purchase_pin TEXT,
    balance DOUBLE PRECISION NOT NULL DEFAULT 0,
    virtual_account_number TEXT,
    virtual_bank_name TEXT,
    kyc_status TEXT NOT NULL DEFAULT 'pending',
    is_admin INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reset_token_hash TEXT,
    reset_token_expires_at BIGINT
);

CREATE TABLE data_plans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network TEXT NOT NULL,
    plan_name TEXT,
    plan TEXT NOT NULL,
    data_size TEXT,
    provider_cost DOUBLE PRECISION NOT NULL DEFAULT 0,
    selling_price DOUBLE PRECISION NOT NULL,
    status TEXT,
    active INTEGER NOT NULL DEFAULT 1,
    provider TEXT,
    provider_code TEXT,
    provider_package_code TEXT,
    provider_package_name TEXT,
    validity TEXT,
    source TEXT,
    last_synced_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(network, plan)
);

CREATE TABLE transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    type TEXT NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    status TEXT NOT NULL,
    reference TEXT,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE sessions (
    sid TEXT PRIMARY KEY,
    sess TEXT NOT NULL,
    expire BIGINT NOT NULL
);

CREATE INDEX idx_sessions_expire ON sessions(expire);

COMMIT;
